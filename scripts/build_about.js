// Builds the "About this lesson" data for the AI & ML lessons from src/ai/about_ml.js and about_now.js.
// Math is rendered here with KaTeX (MIT) to MathML, which browsers draw natively, so the page needs no
// math fonts or scripts. Prints one JS block: const AI_ABOUT = { id: { ...about, math: { lines: [html],
// symbols: [[html, meaning]], example } } }.
const path = require('path');
const katex = require('katex');
const ROOT = path.join(__dirname, '..');
const { AI_ABOUT_ML } = require(path.join(ROOT, 'src', 'ai', 'about_ml.js'));
const { AI_ABOUT_NOW } = require(path.join(ROOT, 'src', 'ai', 'about_now.js'));

const tex = (s, display) => katex.renderToString(s, { output: 'mathml', displayMode: !!display, throwOnError: true });
const out = {};
for (const [id, a] of Object.entries(Object.assign({}, AI_ABOUT_ML, AI_ABOUT_NOW))) {
  const o = Object.assign({}, a);
  if (a.math) o.math = { lines: a.math.lines.map((l) => tex(l, true)), symbols: a.math.symbols.map(([s, m]) => [tex(s), m]), example: a.math.example || [] };
  out[id] = o;
}
process.stdout.write('// @@AI-ABOUT@@ — generated by scripts/build_about.js from src/ai/about_ml.js and about_now.js; edit those, then build.\n'
  + 'const AI_ABOUT = ' + JSON.stringify(out) + ';\n// @@END-AI-ABOUT@@');

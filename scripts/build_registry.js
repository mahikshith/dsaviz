// The problem registry: one entry per problem on the site, for de-duplication. Built from shared/sheet.js,
// shared/catalog.js, shared/tests_spec.js and shared/sql_spec.js, it writes
//   data/problem-registry.json   the entries (tests/registrycheck.js reads it)
//   docs/problems/REGISTRY.md    the same, as a readable table
// Every new problem (a new sheet row, a story, a beginner-track or batch problem, a research idea) goes through
// it: add the problem to the sheet and its spec, run the build, and tests/registrycheck.js fails on a duplicate.
// Entry: id (the problem page id), row (the sheet row id), title, norm (normalized title), aliases (other names
// it goes by, normalized), pattern, diff, story (catalog story id or null), kind ('code' or 'sql'), sig (the I/O
// signature: parameter and return types, a class's methods, or a query's output columns).
// scripts/build_pages.py runs this; `node scripts/build_registry.js --print` prints the JSON instead.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (...p) => fs.readFileSync(path.join(root, ...p), 'utf8');

const STOP = new Set(['a', 'an', 'the', 'of', 'in', 'on', 'to', 'and', 'or', 'for', 'with', 'by', 'from', 'at', 'is', 'are', 'into', 'its', 'it', 'as']);
// Lowercase, no punctuation, no stopwords: "Two Sum II - Input Array Is Sorted" -> "two sum ii input array sorted".
function normTitle(t) {
  return String(t).toLowerCase().replace(/['’`]/g, '').replace(/[^a-z0-9]+/g, ' ').trim().split(' ').filter((w) => w && !STOP.has(w)).join(' ');
}
// Words of a statement, for the near-duplicate check.
function tokens(text) {
  return [...new Set(String(text).toLowerCase().replace(/[^a-z0-9]+/g, ' ').trim().split(' ').filter((w) => w.length > 1 && !STOP.has(w)))];
}

function load() {
  const win = { localStorage: { getItem: () => null, setItem: () => {} } };
  const data = new Function('window', read('shared', 'catalog.js') + '\n' + read('shared', 'sheet.js') + '\n' + read('shared', 'lists.js') + '\nreturn { PROBLEMS, SHEET, SHEET_GROUPS, PROBLEM_LISTS, listIds };')(win);
  const { TEST_SPECS } = require('../shared/tests_spec.js');
  const { SQL_SPECS } = require('../shared/sql_spec.js');
  return Object.assign(data, { TEST_SPECS, SQL_SPECS });
}

// The I/O signature: typed parameters and result from the Python signature, a class's methods, or SQL columns.
function signature(spec, sql) {
  if (sql) return 'sql -> ' + sql.cols.join(', ');
  const py = spec.sig.py;
  const m = py.match(/^(?:async\s+)?def\s+\w+\((.*)\)\s*->\s*(.+):$/);
  if (m) {
    const types = m[1].split(/,(?![^[]*\])/).map((p) => p.trim()).filter(Boolean).map((p) => (p.includes(':') ? p.split(':').slice(1).join(':').trim() : 'any'));
    return '(' + types.join(', ') + ') -> ' + m[2].trim();
  }
  const js = (spec.starter && spec.starter.js) || '';
  const methods = [...js.matchAll(/^ {2}(?:async\s+)?(\w+)\(([^)]*)\)/gm)].filter((x) => x[1] !== 'constructor').map((x) => x[1] + '(' + x[2].split(',').filter((s) => s.trim()).length + ')');
  return 'class {' + methods.join(', ') + '}' + (spec.drive ? ' driven' : '');
}

function build() {
  const D = load();
  const story = {};
  D.PROBLEMS.forEach((p) => { story[p.id] = p; });
  // The practice lists (shared/lists.js) each problem is on: starter, core, all.
  const onLists = {};
  D.PROBLEM_LISTS.forEach((l) => D.listIds(l).forEach((id) => { (onLists[id] = onLists[id] || []).push(l.id); }));
  const entries = D.SHEET.map((r) => {
    const sql = r.pattern === 'SQL' ? D.SQL_SPECS[r.pid] : null;
    const spec = sql ? null : D.TEST_SPECS[r.pid];
    const aliases = new Set();
    const P = r.story ? story[r.story] : null;
    if (P) { aliases.add(normTitle(P.story)); if (normTitle(P.title) !== normTitle(r.name)) aliases.add(normTitle(P.title)); }
    if (normTitle(r.id.replace(/-/g, ' ')) !== normTitle(r.name)) aliases.add(normTitle(r.id.replace(/-/g, ' ')));
    return {
      id: r.pid, row: r.id, title: r.name, norm: normTitle(r.name), aliases: [...aliases].filter(Boolean).sort(),
      pattern: r.pattern, diff: r.diff, story: r.story || null, kind: sql ? 'sql' : 'code',
      sig: spec || sql ? signature(spec, sql) : null,
      words: tokens(sql ? sql.ask : spec ? spec.ask : '').length,
      lists: onLists[r.pid] || []
    };
  });
  return { entries };
}

function markdown(reg) {
  const groups = [];
  reg.entries.forEach((e) => { if (!groups.includes(e.pattern)) groups.push(e.pattern); });
  const cell = (s) => String(s).replace(/\|/g, '\\|');
  let out = '# Problem registry\n\nGenerated by `scripts/build_registry.js` from the master sheet, the catalog and the specs; do not edit by hand. ' +
    'One row per problem (' + reg.entries.length + '). `tests/registrycheck.js` fails when two problems share a normalized title or alias, ' +
    'or share a signature and pattern with near-identical statements. Every new problem goes through here: add it to the sheet and its spec, then build.\n';
  groups.forEach((g) => {
    const rows = reg.entries.filter((e) => e.pattern === g);
    out += '\n## ' + g + ' (' + rows.length + ')\n\n| Page id | Title | Normalized | Also known as | Difficulty | Lists | Signature |\n|---|---|---|---|---|---|---|\n';
    rows.forEach((e) => { out += '| `' + e.id + '` | ' + cell(e.title) + ' | ' + cell(e.norm) + ' | ' + cell(e.aliases.join('; ')) + ' | ' + e.diff + ' | ' + (e.lists || []).join(', ') + ' | `' + cell(e.sig || '') + '` |\n'; });
  });
  return out;
}

if (require.main === module) {
  const reg = build();
  const json = JSON.stringify(reg, null, 1) + '\n';
  if (process.argv.includes('--print')) process.stdout.write(json);
  else {
    fs.mkdirSync(path.join(root, 'data'), { recursive: true });
    fs.mkdirSync(path.join(root, 'docs', 'problems'), { recursive: true });
    fs.writeFileSync(path.join(root, 'data', 'problem-registry.json'), json);
    fs.writeFileSync(path.join(root, 'docs', 'problems', 'REGISTRY.md'), markdown(reg));
    console.log('registry: ' + reg.entries.length + ' problems');
  }
}
module.exports = { build, normTitle, tokens, signature, markdown };
